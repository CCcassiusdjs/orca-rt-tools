def graph_sums(path):
    """Sum of the vertex values, sum of the edge values, pairs of opposite
    edges and parallel edges of a graph file."""
    sc = sw = 0
    state = 1
    pairs = {}
    with open(path) as f:
        for line in f:
            if not line.strip():
                continue
            if state == 1:
                if line.startswith("#"):
                    state = 2
            elif state == 2:
                if line.startswith("#"):
                    state = 3
                else:
                    sc += int(line.split()[1])
            else:
                a, b, w = line.split()
                sw += int(w)
                pairs[(a, b)] = pairs.get((a, b), 0) + 1
    opposite = sum(1 for a, b in pairs if (b, a) in pairs) // 2
    parallel = sum(k - 1 for k in pairs.values())
    return sc, sw, opposite, parallel


def table71(metrics_path, graphs_dir, out_dir):
    """Derived quantities of Table 7.1 for each graph and their minimum,
    mean and maximum: share of edges kept, NoC payload share (= M3_in /
    M3_out, the sum of the vertex values does not change), M1 and M2
    ratios, coefficient of variation of the demands (M2 / mean value),
    cluster sizes and rho = 1 - sum_k |V_k| (|V_k| - 1) / (|V| (|V| - 1)),
    the expected share of edges between clusters when the endpoints of each
    edge are an ordered pair of distinct vertices drawn uniformly."""
    with open(metrics_path) as f:
        src = json.load(f)
    n = src["n"]
    rows = []
    for r in src["rows"]:
        c = r["calc"]
        v = r["V"]
        sc, sw, opposite, parallel = graph_sums(os.path.join(graphs_dir, f"10_{v}.txt"))
        d = {"V": v, "E": c["E"], "sum_c": sc, "sum_w": sw, "opposite_pairs": opposite,
             "parallel_edges": parallel, "M1": c["M1"], "M2": c["M2"], "M3": c["M3"],
             "cv_in": c["M2"] / (sc / v)}
        for p in ("mc", "mp"):
            o = c[p]
            d[p] = {"kept_percent": 100 * o["E"] / c["E"], "noc_percent": 100 * c["M3"] / o["M3"],
                    "M1_ratio": o["M1"] / c["M1"], "M2_ratio": o["M2"] / c["M2"], "cv": o["M2"] / (sc / n),
                    "E": o["E"], "M1": o["M1"], "M2": o["M2"], "M3": o["M3"]}
            sizes = o.get("cluster_sizes")
            if sizes is not None:
                d[p]["cluster_sizes"] = sizes
                d[p]["rho_percent"] = 100 * (1 - sum(x * (x - 1) for x in sizes) / (v * (v - 1)))
                d[p]["rho_minus_kept"] = d[p]["rho_percent"] - d[p]["kept_percent"]
        rows.append(d)

    def agg(p, k):
        xs = [d[p][k] for d in rows]
        return {"min": min(xs), "mean": st.mean(xs), "max": max(xs)}

    def rng(k):
        xs = [d[k] for d in rows]
        return {"min": min(xs), "max": max(xs)}

    keys = ("kept_percent", "noc_percent", "M1_ratio", "M2_ratio", "cv", "M3")
    summary = {p: {k: agg(p, k) for k in keys} for p in ("mc", "mp")}
    summary["input"] = {k: rng(k) for k in ("E", "M1", "M2", "M3", "cv_in", "opposite_pairs", "parallel_edges")}
    small = [d for d in rows if d["V"] <= 100]
    if small:
        summary["input_v_le_100"] = {k: {"min": min(d[k] for d in small), "max": max(d[k] for d in small)}
                                     for k in ("opposite_pairs", "parallel_edges")}
    if all("cluster_sizes" in d["mc"] for d in rows):
        three = [d["V"] for d in rows if d["mc"]["cluster_sizes"] == [1, 1, 1, d["V"] - 3]]
        summary["cluster_sizes"] = {
            "min_comm_three_single_tasks": len(three),
            "min_comm_other_graphs": {str(d["V"]): d["mc"]["cluster_sizes"] for d in rows if d["V"] not in three},
            "max_abs_rho_minus_kept": max(abs(d[p]["rho_minus_kept"]) for d in rows for p in ("mc", "mp")),
            "max_abs_rho_minus_kept_v_ge_200": max([abs(d[p]["rho_minus_kept"]) for d in rows if d["V"] >= 200
                                                    for p in ("mc", "mp")], default=None),
        }
    m = {"n": n, "graphs": len(rows), "source": os.path.basename(metrics_path),
         "cells_agree": src.get("summary", {}).get("cells_agree"), "rows": rows, "summary": summary}
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "metrics.json"), "w") as f:
        json.dump(m, f, indent=1)

    cols = ["V", "E", "sum_c", "sum_w", "opposite_pairs", "parallel_edges", "cv_in"]
    pcols = ["E", "kept_percent", "noc_percent", "M1_ratio", "M2_ratio", "cv", "M3", "rho_percent"]
    write_csv(os.path.join(out_dir, "table71.csv"),
              cols + [f"{p}_{k}" for p in ("mc", "mp") for k in pcols],
              [[d[k] for k in cols] + [d[p].get(k) for p in ("mc", "mp") for k in pcols] for d in rows])
    write_csv(os.path.join(out_dir, "sizes.csv"), ["V", "criterion", "cluster_sizes", "rho_percent", "kept_percent"],
              [[d["V"], crit, " ".join(map(str, d[p].get("cluster_sizes", []))), d[p].get("rho_percent"),
                d[p]["kept_percent"]] for d in rows for p, crit in (("mc", "MIN_COMM"), ("mp", "MAX_PROC"))])

    def stats(p, k, dg):
        s = summary[p][k]
        return [thin(s["min"], dg), thin(s["mean"], dg), thin(s["max"], dg)]

    def irng(k, dg):
        s = summary["input"][k]
        return f"{thin(s['min'], dg)}--{thin(s['max'], dg)}"

    lines = [
        ("Edges kept, $|E_{\\mathrm{out}}|/|E_{\\mathrm{in}}|$ (\\%)", f"$|E|$ = {irng('E', 0)}", "kept_percent", 1),
        ("NoC payload, $W_{\\mathrm{NoC}}/\\sum w$ (\\%)", "100", "noc_percent", 1),
        ("M1 ratio, $\\mathrm{M1}_{\\mathrm{out}}/\\mathrm{M1}_{\\mathrm{in}}$", f"M1 = {irng('M1', 0)} bytes",
         "M1_ratio", 2),
        ("M2 ratio, $\\mathrm{M2}_{\\mathrm{out}}/\\mathrm{M2}_{\\mathrm{in}}$", f"M2 = {irng('M2', 0)} cycles",
         "M2_ratio", 1),
        ("Coefficient of variation, $\\mathrm{M2}/\\bar{c}$", irng("cv_in", 2), "cv", 2),
        ("M3 (cycles/byte)", irng("M3", 3), "M3", 3),
    ]
    write_tex(os.path.join(out_dir, "tab-table71-rows.tex"),
              ["    " + " & ".join([lab, inp] + stats("mc", k, dg) + stats("mp", k, dg)) + r" \\"
               for lab, inp, k, dg in lines])

    def coords(p, k, dg):
        return " ".join(f"({d['V']},{d[p][k]:.{dg}f})" for d in rows)

    write_tex(os.path.join(out_dir, "fig-table71-coords.tex"), [
        "% (a) NoC payload: MIN-COMM, MAX-PROC",
        f"\\addplot[mc] coordinates {{{coords('mc', 'noc_percent', 2)}}};",
        f"\\addplot[mp] coordinates {{{coords('mp', 'noc_percent', 2)}}};",
        "% (b) M1 ratio: MIN-COMM, MAX-PROC",
        f"\\addplot[mc] coordinates {{{coords('mc', 'M1_ratio', 4)}}};",
        f"\\addplot[mp] coordinates {{{coords('mp', 'M1_ratio', 4)}}};",
        "% (c) coefficient of variation: MIN-COMM, MAX-PROC, input",
        f"\\addplot[mc] coordinates {{{coords('mc', 'cv', 4)}}};",
        f"\\addplot[mp] coordinates {{{coords('mp', 'cv', 4)}}};",
        "\\addplot[inp] coordinates {" + " ".join(f"({d['V']},{d['cv_in']:.4f})" for d in rows) + "};",
    ])
    return m


