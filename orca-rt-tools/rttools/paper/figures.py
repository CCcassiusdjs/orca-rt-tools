def thin(x, d=0):
    """Number with thin spaces (LaTeX \\,) between thousands."""
    return f"{x:,.{d}f}".replace(",", "\\,")


def half_up(x):
    return int(math.floor(x + 0.5))


def write_csv(path, header, rows):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            w.writerow(r)


def write_tex(path, lines):
    with open(path, "w") as f:
        f.write("% generated by python -m rttools.paper.figures; do not edit\n")
        f.write("\n".join(lines) + "\n")


