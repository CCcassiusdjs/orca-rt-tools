# layout of the 10-task graph of the contraction figure (cm) and the
# side of each label
POS = {"A": (0, 1.0), "B": (1.12, 2.0), "D": (2.24, 2.0), "F": (3.36, 2.0), "G": (4.48, 2.0),
       "C": (1.12, 0.0), "E": (2.24, 0.0), "H": (3.36, 0.6), "I": (3.36, -0.6), "J": (5.6, 1.0)}
CPOS = {"A": "left", "B": "above", "D": "above", "F": "above", "G": "above", "C": "below",
        "E": "above", "H": "above", "I": "below", "J": "above"}
WPOS = {"A-B": "below right", "A-C": "below left", "B-D": "below", "C-E": "above", "D-F": "below",
        "E-H": "below right", "E-I": "below left", "F-G": "below", "G-J": "below left",
        "H-J": "above", "I-J": "below right"}
HULL_COLORS = ["cA", "cB", "cC", "cE"]


def contraction_run(path, criterion, n):
    """Contracts the graph to n clusters; returns the demand of each task,
    the edges, the step of each contracted edge (by the label u-v of the
    input edge), the clusters with their demand, the cluster of each task
    and the payload between clusters."""
    g = load_graph(path)
    lam = {v._data["label"]: int(v._data["wcet"]) for v in g._nodes}
    f = getattr(CriteriaICC, criterion)
    steps = {}
    k = 0
    while len(g._nodes) > n:
        e = f(g)
        k += 1
        steps[e._data["label"]] = k
        g = GraphICC.collapse(g, f)
    clusters = {v._data["label"]: int(v._data["wcet"]) for v in g._nodes}
    member = {t: cl for cl in clusters for t in cl.split(":")}
    edges = [(e._from._data["label"], e._to._data["label"], int(e._data["payload"]))
             for e in load_graph(path)._edges]
    wnoc = sum(w for u, v, w in edges if member[u] != member[v])
    return {"demand": lam, "edges": edges, "steps": steps, "clusters": clusters, "member": member,
            "w_noc": wnoc, "M2": gde.node_standard_deviation(g), "max_demand": max(clusters.values()),
            "out_edges": len(g._edges), "out_payload": sum(int(e._data["payload"]) for e in g._edges)}


def contraction_panel(r, crit, title, xshift):
    """TikZ scope of one panel of the contraction figure."""
    px = {"MIN_COMM": "mc", "MAX_PROC": "mp", "MAX_COMM": "xc", "MIN_PROC": "np"}[crit]
    lam, edges, steps, clusters, member = r["demand"], r["edges"], r["steps"], r["clusters"], r["member"]
    out = [f"  % {crit}: steps {steps}; clusters {clusters}; W_NoC {r['w_noc']}",
           f"  \\begin{{scope}}[xshift={xshift}cm]",
           f"    \\node[anchor=west, font=\\footnotesize\\bfseries] at (-0.95, 2.75) {{{title}}};"]
    for v, (x, y) in POS.items():
        out.append(f"    \\node[tk] ({px}{v}) at ({x},{y}) {{{v}}};")
        out.append(f"    \\node[dm, {CPOS[v]}=0pt of {px}{v}] {{{lam[v]}}};")
    order = sorted(clusters, key=lambda c: min(POS[v][0] for v in c.split(":")) * 10
                   - max(POS[v][1] for v in c.split(":")))
    out.append("    \\begin{scope}[on background layer]")
    for i, cl in enumerate(order):
        vs = cl.split(":")
        col = HULL_COLORS[i]
        for u, v, w in edges:
            if f"{u}-{v}" in steps and u in vs and v in vs:
                out.append(f"      \\draw[hull={col}] ({px}{u}.center) -- ({px}{v}.center);")
        if len(vs) == 1:
            out.append(f"      \\fill[{col}!22] ({px}{vs[0]}) circle (3.5mm);")
    out.append("    \\end{scope}")
    for u, v, w in edges:
        lab = f"{u}-{v}"
        style = "noc" if member[u] != member[v] else ("con" if lab in steps else "intra")
        gap = "1.5mm" if lab in steps else "0.4mm"
        line = f"    \\draw[{style}] ({px}{u}) -- node[wl, {WPOS[lab]}={gap}] {{{w}}}"
        if lab in steps:
            line += f" node[stp] {{{steps[lab]}}}"
        out.append(line + f" ({px}{v});")
    cl_txt = ", ".join(f"{''.join(sorted(cl.split(':')))}~{clusters[cl]}"
                       for cl in sorted(order, key=lambda c: min(c.split(':'))))
    out.append(f"    \\node[anchor=north west, font=\\scriptsize, align=left] at (-0.95, -1.1) "
               f"{{Cluster demand (cycles): {cl_txt}\\\\$W_{{\\mathrm{{NoC}}}}={r['w_noc']}$ bytes}};")
    out.append("  \\end{scope}")
    return out


CRITERIA_TEXT = {
    "MIN_COMM": (r"$\arg\max_{e \in E} w(e)$",
                 "Heaviest payload to local memory first; Kruskal, decreasing $w$ (single linkage)"),
    "MAX_COMM": (r"$\arg\min_{e \in E} w(e)$", "Lightest payload to local memory first; Kruskal, increasing $w$"),
    "MIN_PROC": (r"$\arg\max_{(u,v) \in E} c(u)+c(v)$",
                 "Largest-demand pair first; one cluster absorbs the heaviest tasks"),
    "MAX_PROC": (r"$\arg\min_{(u,v) \in E} c(u)+c(v)$",
                 "Smallest-demand pair first; cluster demands approach each other"),
}


def contraction(path, n, out_dir, panels=("MIN_COMM", "MAX_PROC")):
    runs = {c: contraction_run(path, c, n) for c in CRITERIA}
    g = load_graph(path)
    m = {"graph": os.path.basename(path), "n": n,
         "total_demand": sum(int(v._data["wcet"]) for v in g._nodes),
         "total_payload": sum(int(e._data["payload"]) for e in g._edges),
         "criteria": {c: {"max_demand": r["max_demand"], "M2": r["M2"], "w_noc": r["w_noc"],
                          "out_edges": r["out_edges"], "out_payload": r["out_payload"],
                          "steps": r["steps"],
                          "clusters": {"".join(sorted(k.split(":"))): v for k, v in r["clusters"].items()}}
                      for c, r in runs.items()}}
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "contraction.json"), "w") as f:
        json.dump(m, f, indent=1)
    write_csv(os.path.join(out_dir, "criteria.csv"),
              ["criterion", "max_demand", "M2", "w_noc", "clusters", "steps"],
              [[c, r["max_demand"], r["M2"], r["w_noc"],
                " ".join(f"{k}={v}" for k, v in m["criteria"][c]["clusters"].items()),
                " ".join(f"{e}:{s}" for e, s in r["steps"].items())] for c, r in runs.items()])
    rows = []
    for c in CRITERIA:
        r = runs[c]
        sel, eff = CRITERIA_TEXT[c]
        rows.append(f"    {DASH[c]} & {sel} & {eff} & {thin(r['max_demand'])} & {thin(r['M2'])} & "
                    f"{thin(r['w_noc'])} \\\\")
    write_tex(os.path.join(out_dir, "tab-criteria-rows.tex"), rows)
    body = []
    for i, c in enumerate(panels):
        title = f"({'ab'[i]}) {DASH[c]}"
        body += contraction_panel(runs[c], c, title, 0 if i == 0 else 6.95)
    write_tex(os.path.join(out_dir, "fig-contraction-body.tex"), body)
    return m


