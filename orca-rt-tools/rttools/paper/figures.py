# Gantt layout (cm and ms)
XCM = 5.3            # cm per ms
MIN_LABEL_CM = 0.14  # write the letter when the bar is this wide
ROW_H = 0.82
RTL_H = 0.36
EST_H = 0.20
EST_GAP = 0.06
TASK_COLORS = ["cA", "cB", "cC", "cE"]


def pe_xy(pe):
    """Mesh coordinates (x, y) of a PE label of config.json (the labels
    follow the log of commit 4c299fc, with X and Y swapped; the same rule
    as rttools.paper.exp23.write_figure)."""
    a, b = pe.split("-")
    return int(b), int(a)


def gantt(tr, cfg, clk, window, resp):
    """Coordinates of the Gantt of one hyperperiod (window [W0, W1) in raw
    units): RTL bars, ORT/BENCH estimate bars, releases, responses of the
    two first iterations of the window and the deadline of the first."""
    w0, w1 = window
    hp_ms = (w1 - w0) * tr.unit.seconds * 1e3
    n_it = cfg["iterations_per_hyperperiod"]

    def ms(raw):
        return (raw - w0) * tr.unit.seconds * 1e3

    rows = sorted(cfg["clusters"].items(), key=lambda kv: (pe_xy(kv[0])[1], pe_xy(kv[0])[0]))
    color = {}
    for _, cl in rows:
        for i, t in enumerate(cl):
            color[t] = TASK_COLORS[i]
    out, bars = [], []
    emit = out.append
    busy_cycles = {}
    for i, (lane, cl) in enumerate(rows):
        y = -i * ROW_H
        busy = 0
        for s in tr.lane_slices(lane):
            if s.label == "IDLE" or s.end <= w0 or s.start >= w1:
                continue
            a, b = max(s.start, w0), min(s.end, w1)
            busy += b - a
            x0, x1 = ms(a), ms(b)
            bars.append(["rtl", cl, s.label, s.start, s.end, x0, x1])
            emit(f"\\draw[rtl,fill={color[s.label]}!85] ({x0:.6f},{y:.2f}) rectangle ({x1:.6f},{y + RTL_H:.2f});"
                 f" % {s.label} {s.start}-{s.end} ns")
            if (x1 - x0) * XCM >= MIN_LABEL_CM:
                small = ",font=\\tiny" if (x1 - x0) * XCM < 0.25 else ""
                emit(f"\\node[tl{small}] at ({(x0 + x1) / 2:.6f},{y + RTL_H / 2:.2f}) {{{s.label}}};")
        busy_cycles[cl] = X.exact(round(clk.cycles(busy) / n_it, 6))

    est = cfg["estimate"]
    sched = X.cpu_sequence(cfg)
    phase_cycles = int(cfg["release_period_s"] * cfg["clock_hz"])
    to_ms = 1e3 / cfg["clock_hz"]
    for i, (lane, cl) in enumerate(rows):
        y = -i * ROW_H - EST_GAP - EST_H
        for k in range(n_it):
            origin = k * phase_cycles
            for name, _ in est["clusters"][cl]:
                start, finish = sched[name]["start"], sched[name]["finish"]
                a = (origin + start) * to_ms
                b = (origin + finish) * to_ms
                bars.append(["estimate", cl, name, start, finish, a, b])
                emit(f"\\draw[est,fill={color[name]}!30,postaction={{pattern=north east lines,"
                     f"pattern color={color[name]}!70!black}}] ({a:.6f},{y:.2f}) rectangle ({b:.6f},{y + EST_H:.2f});"
                     f" % {name} {start}-{finish} cycles, phase {k}")
                if (b - a) * XCM >= 0.3:
                    emit(f"\\node[el] at ({(a + b) / 2:.6f},{y + EST_H / 2:.2f}) {{{name}}};")

    rel = [mk.time for mk in tr.lane_marks("TRIGGER") if w0 <= mk.time < w1]
    top = RTL_H + 0.12
    bottom = -(len(rows) - 1) * ROW_H - EST_GAP - EST_H - 0.08
    for t in rel:
        x = ms(t)
        emit(f"\\draw[rel] ({x:.6f},{bottom:.2f}) -- ({x:.6f},{top:.2f}); % TRIGGER {t} ns")
        emit(f"\\fill[black!70] ({x:.6f},{top:.2f}) -- ++(-0.015,0.1) -- ++(0.03,0) -- cycle;")

    for i, (lane, cl) in enumerate(rows):
        y = -i * ROW_H
        x, yy = pe_xy(lane)
        emit(f"\\node[rowl] at (-0.015,{y + RTL_H / 2:.2f}) {{PE ({x},{yy}) {cl}}};")
        emit(f"\\node[estl] at (-0.015,{y - EST_GAP - EST_H / 2:.2f}) {{estimate}};")
    ya = bottom - 0.04
    xmax = hp_ms + 0.06
    emit(f"\\draw[black!70] (0,{ya:.2f}) -- ({xmax:.2f},{ya:.2f});")
    w0_ms = w0 * tr.unit.seconds * 1e3
    for k in range(int(round(hp_ms / 0.25)) + 1):
        x = k * 0.25
        emit(f"\\draw[black!70] ({x:.2f},{ya:.2f}) -- ++(0,-0.08);")
        lab = f"{w0_ms + x:.2f}"
        cyc = "" if k % 2 else f"\\\\[-1pt]\\textcolor{{black!55}}{{{int(x * cfg['clock_hz'] / 1e6)}k}}"
        emit(f"\\node[tick] at ({x:.2f},{ya - 0.1:.2f}) {{{lab}{cyc}}};")
    emit(f"\\node[anchor=north east,align=right,font=\\scriptsize] at (-0.075,{ya - 0.1:.2f})"
         f" {{time (ms)\\\\[-1pt]\\textcolor{{black!55}}{{cycles from {w0_ms:g}~ms}}}};")
    deadline = rel[0] + clk.raw(cfg["response_deadline_s"])
    xd = ms(deadline)
    emit(f"\\draw[dl] ({xd:.6f},{bottom:.2f}) -- ({xd:.6f},{top + 0.95:.2f});"
         f" % deadline = TRIGGER {rel[0]} ns + {cfg['response_deadline_s'] * 1e3:g} ms")
    win = [r for r in resp if w0 <= r["start"] < w1][:2]
    jy = -(len(rows) - 1) * ROW_H + RTL_H
    brackets = []
    for lvl, r in enumerate(win):
        s, e = r["start"], r["end"]
        cyc = int(math.floor(clk.cycles(e - s)))
        txt = f"{(e - s) * tr.unit.seconds * 1e3:.3f}~ms ({thin(cyc)} cycles)"
        yb = top + 0.32 + 0.33 * (1 - lvl)
        xs, xe = ms(s), ms(e)
        brackets.append({"iteration": r["iteration"], "start": s, "end": e, "cycles": cyc,
                         "ms": r["response_ms"]})
        emit(f"\\draw[resp] ({xs:.6f},{yb:.2f}) -- ({xe:.6f},{yb:.2f});"
             f" % first dispatch of A {s} ns to exit of J {e} ns")
        emit(f"\\draw[drop] ({xs:.6f},{yb:.2f}) -- ({xs:.6f},{RTL_H:.2f});")
        emit(f"\\draw[drop] ({xe:.6f},{yb:.2f}) -- ({xe:.6f},{jy:.2f});")
        emit(f"\\node[rlab] at ({(xs + xe) / 2:.6f},{yb:.2f}) {{response {txt}}};")
    emit(f"\\node[anchor=south east,font=\\scriptsize,text=cD!80!black,fill=white,inner sep=1pt] at "
         f"({xd - 0.01:.6f},{top + 0.82:.2f}) {{deadline}};")
    info = {"window_raw": [w0, w1], "busy_cycles_per_iteration": busy_cycles, "releases_raw": rel,
            "deadline_raw": deadline, "responses": brackets}
    return out, bars, info


def iterations(tr, cfg, clk, resp):
    """Coordinates of the response of each iteration: x = release instant
    of A (TRIGGER line before the first dispatch), y = response (ms)."""
    rel = sorted(mk.time for mk in tr.lane_marks("TRIGGER"))
    pts = []
    for r in resp:
        before = [t for t in rel if t <= r["start"]]
        release_ms = (before[-1] if before else r["start"]) * tr.unit.seconds * 1e3
        pts.append({"iteration": r["iteration"], "release_ms": release_ms, "response_ms": r["response_ms"],
                    "response_cycles": r["response_cycles"]})
    mx = max(pts, key=lambda p: p["response_ms"])
    deadline_ms = cfg["response_deadline_s"] * 1e3
    lines = [f"        ({p['release_ms']:.1f},{p['response_ms']:.6f}) % it {p['iteration']} "
             f"{p['response_cycles']} cycles" for p in pts]
    lines.append(f"% maximum: (axis cs:<x0>,{mx['response_ms']}) -- (axis cs:<x1>,{mx['response_ms']}); "
                 f"max {mx['response_ms']:.3f}~ms ({thin(mx['response_cycles'])} cycles, "
                 f"{100 * mx['response_ms'] / deadline_ms:.0f}\\,\\% of the deadline)")
    info = {"points": pts, "max_ms": mx["response_ms"], "max_cycles": mx["response_cycles"],
            "max_deadline_percent": 100 * mx["response_ms"] / deadline_ms}
    return lines, info


def flows(tr, cfg, clk, fcfg):
    """Rows of the flow table: payload, hops m of XY routing, flits p,
    zero-load latency L0 = a (m + 1) + p + b, latency measured per packet,
    release and deadline of the phase model (rttools/modules/instances/
    release.py: f^ of the source and P + s^ of the target), send and
    arrival offsets from the start of the phase in which the source sends
    (half cycles rounded up)."""
    window = X.phase_windows(cfg)
    period_raw = clk.raw(cfg["release_period_s"])
    router = fcfg["router"]
    t82 = {r["flow"]: r for r in X.tab82(cfg, tr, clk)}
    rows = []
    for f in cfg["flows"]:
        tag = "TAG " + f["tag"]
        sends = sorted(mk.time for mk in tr.lane_marks(f["src_pe"]) if mk.kind == "send" and mk.label == tag)
        recvs = sorted(mk.time for mk in tr.lane_marks(f["dst_pe"]) if mk.kind == "recv" and mk.label == tag)
        pairs = list(zip(sends, recvs))
        lat = [clk.cycles(b - a) for a, b in pairs]
        if any(x <= 0 for x in lat):
            raise ValueError(f"{f['name']}: receive before send")
        send_off = [clk.cycles(a - (a // period_raw) * period_raw) for a, _ in pairs]
        recv_off = [clk.cycles(b - (a // period_raw) * period_raw) for a, b in pairs]
        payload = int(f["tag"])
        (sx, sy), (dx, dy) = pe_xy(f["src_pe"]), pe_xy(f["dst_pe"])
        m = abs(sx - dx) + abs(sy - dy)
        p = math.ceil((router["header_bytes"] + 4 * math.ceil(payload / 4)) / router["flit_bytes"])
        l0 = router["cycles_per_hop"] * (m + 1) + p + router["extra_cycles"]
        t = t82.get(f["name"], {})
        rows.append({
            "flow": f["name"], "source": f["source"], "target": f["target"], "payload": payload,
            "hops": m, "flits": p, "L0": l0,
            "latency_min": X.exact(min(lat)), "latency_max": X.exact(max(lat)), "packets": len(pairs),
            "sends": len(sends), "receives": len(recvs),
            "latency_matches_tab82": (t.get("latency_min_cycles"), t.get("latency_max_cycles"))
            == (X.exact(min(lat)), X.exact(max(lat))),
            "latency_min_minus_L0": X.exact(min(lat)) - l0,
            "release": X.exact(window[f["name"]][0]),
            "deadline": X.exact(window[f["name"]][1]),
            "send_min": half_up(min(send_off)), "send_max": half_up(max(send_off)),
            "arrival_max": half_up(max(recv_off)),
        })
    lines = []
    for r in rows:
        lines.append(f"    {r['flow']} & {r['source']}$\\to${r['target']} & {thin(r['payload'])} & {r['hops']} & "
                     f"{thin(r['flits'])} & {thin(r['L0'])} & {thin(r['latency_min'])}--{thin(r['latency_max'])} & "
                     f"{thin(r['release'])} & {thin(r['send_min'])}--{thin(r['send_max'])} & "
                     f"{thin(r['deadline'])} & {thin(r['arrival_max'])} \\\\")
    return lines, rows


def exp23_figures(log, cfg, fcfg, out_dir, join=None):
    tr = X.load(log, cfg)
    clk = X.Clock(tr.unit, cfg["clock_hz"])
    windows = X.hyperperiods(tr, cfg, clk)
    rule = X.join_rule(cfg, join)
    resp = X.responses(tr, cfg, clk, rule)
    g_lines, bars, g_info = gantt(tr, cfg, clk, windows[0], resp)
    i_lines, i_info = iterations(tr, cfg, clk, resp)
    f_lines, f_rows = flows(tr, cfg, clk, fcfg)
    measured = X.cpu_per_iteration(tr, cfg, clk, windows[:1])
    g_info["busy_equals_tab83"] = all(math.isclose(g_info["busy_cycles_per_iteration"][c], measured[c]["mean"])
                                      for c in g_info["busy_cycles_per_iteration"])
    m = {"log": os.path.basename(log), "unit": tr.unit.name, "swap_xy": bool(tr.meta["swap_xy"]),
         "join_rule": rule, "gantt": g_info, "iterations": i_info, "flows": f_rows}
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "metrics.json"), "w") as f:
        json.dump(m, f, indent=1)
    write_csv(os.path.join(out_dir, "gantt.csv"), ["kind", "cluster", "task", "start", "end", "x0_ms", "x1_ms"],
              bars)
    write_csv(os.path.join(out_dir, "iterations.csv"), ["iteration", "release_ms", "response_ms", "response_cycles"],
              [[p["iteration"], p["release_ms"], p["response_ms"], p["response_cycles"]] for p in i_info["points"]])
    cols = list(f_rows[0].keys())
    write_csv(os.path.join(out_dir, "flows.csv"), cols, [[r[c] for c in cols] for r in f_rows])
    write_tex(os.path.join(out_dir, "fig-gantt-body.tex"), g_lines)
    write_tex(os.path.join(out_dir, "fig-iterations-coords.tex"), i_lines)
    write_tex(os.path.join(out_dir, "tab-flows-rows.tex"), f_lines)
    return m


